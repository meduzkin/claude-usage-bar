#!/bin/bash
# Prints EmbeddedScripts.swift: sessions.sh and the two notification hooks
# as Swift raw string literals (see ensureSupportScripts() in Sessions.swift).
set -euo pipefail
cd "$(dirname "$0")"
emit() {
  local name="$1" file="$2"
  if grep -q '"""#' "$file"; then echo "embed-scripts: $file contains \"\"\"# — cannot embed" >&2; exit 1; fi
  printf 'let %s = #"""\n' "$name"
  cat "$file"
  printf '"""#\n\n'
}
echo "// Generated by embed-scripts.sh from the scripts in this repo. Do not edit."
echo
emit EMBEDDED_SESSIONS_SH sessions.sh
emit EMBEDDED_CLAUDE_NOTIFY_SH scripts/claude-notify.sh
emit EMBEDDED_CLAUDE_NOTIFY_CANCEL_SH scripts/claude-notify-cancel.sh
emit EMBEDDED_JIRA_PY jira.py
